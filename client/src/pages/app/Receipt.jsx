import { useEffect, useState } from 'react'
import { Link, useParams } from 'react-router-dom'
import { ArrowLeft, Printer } from 'lucide-react'
import api, { errorMessage } from '../../services/api.js'
import { useAuth } from '../../context/AuthContext.jsx'
import { formatDate } from '../../utils/constants.js'
import Button from '../../components/ui/Button.jsx'
import Alert from '../../components/ui/Alert.jsx'
import PageLoader from '../../components/ui/PageLoader.jsx'

function Row({ label, children }) {
  return (
    <div className="flex justify-between gap-6 border-b border-slate-100 py-2.5 text-sm">
      <span className="text-slate-500">{label}</span>
      <span className="text-right font-medium text-ink">{children || '-'}</span>
    </div>
  )
}

// Printable receipt. "Print" lets you save it as a PDF from the browser's print window.
export default function Receipt() {
  const { id } = useParams()
  const { user } = useAuth()
  const [request, setRequest] = useState(null)
  const [error, setError] = useState('')

  useEffect(() => {
    api.get(`/requests/${id}`).then((r) => setRequest(r.data.data.request)).catch((e) => setError(errorMessage(e)))
  }, [id])

  if (!request) return error ? <Alert>{error}</Alert> : <PageLoader />

  const r = request
  const resolvedAt = [...r.statusHistory].reverse().find((h) => h.status === 'Resolved')?.at

  return (
    <>
      <div className="no-print mb-6 flex items-center justify-between">
        <Link to={`/${user.role}/requests/${id}`} className="inline-flex items-center gap-1.5 text-sm font-medium text-slate-600 hover:text-ink">
          <ArrowLeft className="h-4 w-4" aria-hidden="true" /> Back to request
        </Link>
        {r.status === 'Resolved' && (
          <Button onClick={() => window.print()}><Printer className="h-4 w-4" aria-hidden="true" /> Print or save as PDF</Button>
        )}
      </div>

      {r.status !== 'Resolved' ? (
        <Alert>A receipt is available only after the request is resolved.</Alert>
      ) : (
        <div className="mx-auto max-w-xl rounded-xl border border-slate-200 bg-white p-8 print-plain">
          <div className="mb-6 flex items-start justify-between border-b border-slate-200 pb-5">
            <div>
              <p className="text-2xl font-bold tracking-tight text-ink">VehicleCare</p>
              <p className="text-sm text-slate-500">Service receipt</p>
            </div>
            <div className="text-right text-sm">
              <p className="font-semibold text-ink">Receipt no. {String(r._id).slice(-8).toUpperCase()}</p>
              <p className="text-slate-500">{resolvedAt ? formatDate(resolvedAt) : ''}</p>
            </div>
          </div>

          <Row label="Customer">{r.customer?.name}</Row>
          <Row label="Vehicle">{r.vehicle ? `${r.vehicle.make} ${r.vehicle.model} (${r.vehicle.registrationNumber})` : 'Removed'}</Row>
          <Row label="Service">{r.category} ({r.type === 'maintenance' ? 'maintenance' : 'breakdown'})</Row>
          <Row label="Location">{r.address}</Row>
          <Row label="Service provider">{r.provider?.name}</Row>
          <Row label="Reported on">{formatDate(r.createdAt)}</Row>
          <Row label="Estimated cost">{r.estimatedCost != null ? `₹${r.estimatedCost}` : ''}</Row>
          <Row label="Provider notes">{r.providerNotes}</Row>

          <div className="mt-6 flex items-center justify-between rounded-lg bg-slate-50 p-4">
            <span className="font-semibold text-ink">Total paid</span>
            <span className="text-2xl font-bold text-ink">{r.finalCost != null ? `₹${r.finalCost}` : 'Not entered'}</span>
          </div>
          <p className="mt-6 text-center text-xs text-slate-400">Generated by VehicleCare. This is a project demonstration receipt.</p>
        </div>
      )}
    </>
  )
}
